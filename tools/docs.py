def stats(ident):
    e = ENTITIES[ident]
    c = e['components']
    hp = c.get('minecraft:health', {}).get('value', '')
    atk = c.get('minecraft:attack', {}).get('damage', '–')
    speed = c.get('minecraft:movement', {}).get('value', '')
    fam = ', '.join(x for x in c.get('minecraft:type_family', {}).get('family', []) if x not in ('mob',))
    loot = c.get('minecraft:loot', {}).get('table', '')
    return hp, atk, speed, fam, loot


def drops(loot):
    tbl = LOOT.get(loot)
    if not tbl:
        return '–'
    out_ = []
    for pool in tbl.get('pools', []):
        entries = pool.get('entries', [])
        total = sum(x.get('weight', 1) for x in entries) or 1
        for x in entries:
            if x.get('type') != 'item':
                continue
            cnt = ''
            for fn in x.get('functions', []):
                if fn.get('function') == 'set_count':
                    c = fn['count']
                    cnt = f"{c['min']}-{c['max']}" if isinstance(c, dict) and c['min'] != c['max'] else f"{c['min'] if isinstance(c, dict) else c}"
            chance = x.get('weight', 1) / total
            out_.append(f"{item_name(x['name'])}{' ×' + cnt if cnt and cnt != '1' else ''}{f' ({chance * 100:.0f}%)' if chance < 0.999 else ''}")
    return ', '.join(out_) or '–'


