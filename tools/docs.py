def spawning(ident):
    extra = ORIGIN.get(ident, '')
    r = SPAWN.get(ident)
    if not r:
        return extra or 'summoned only'
    return natural(r) + (f'; also {extra}' if extra else '')


def natural(r):
    out_ = []
    for cond in r.get('conditions', []):
        b = cond.get('minecraft:brightness_filter')
        when = ''
        if b:
            when = 'at night / in the dark' if b.get('max', 15) <= 7 else 'by day' if b.get('min', 0) >= 8 else ''
        where = 'on the surface' if 'minecraft:spawns_on_surface' in cond else 'underwater' if 'minecraft:spawns_underwater' in cond else ''
        bf = cond.get('minecraft:biome_filter', {})
        tags = [x.get('value') for x in bf.get('any_of', [])] or [bf.get('value')] if bf else []
        herd = cond.get('minecraft:herd', {})
        group = f", groups of {herd.get('min_size', 1)}-{herd.get('max_size', 1)}" if herd else ''
        out_.append(f"{where} {when} in {', '.join(t for t in tags if t)} biomes{group}".replace('  ', ' ').strip())
    return '; '.join(out_)


