def effects(lst):
    return ', '.join(f"{e[0].replace('_', ' ')} {e[2] + 1 if e[2] else ''}".replace('  ', ' ').strip() + f' ({e[1]:g}s)' for e in lst)


def describe(s):
    """A spell-engine recipe in plain words."""
    if not s:
        return ''
    t = s['t']
    d = s.get('d')
    parts = []
    shapes = ['orb', 'shard', 'blade', 'needle']
    if t == 'bolt':
        n = s.get('n', 1)
        parts.append(f"{n} {shapes[s.get('shape', 0)]} bolt{'s' if n > 1 else ''}" + (f" in a {s['spread']:g}° fan" if s.get('spread') else ''))
        if d:
            parts.append(f'{d:g} damage{" each" if n > 1 else ""}')
        if s.get('aoe'):
            parts.append(f"bursts in a {s['aoe']:g}-block radius")
        if s.get('pierce'):
            parts.append(f"pierces {s['pierce']} foe{'s' if s['pierce'] > 1 else ''}")
        if s.get('grav'):
            parts.append('lobbed (falls)')
    elif t == 'beam':
        parts.append(f"instant beam, {s.get('range', 20)} blocks long, {s.get('width', 1.0):g} wide")
        if d:
            parts.append(f'{d:g} damage')
    elif t == 'wave':
        lanes = f", {s['lanes']} lanes wide" if s.get('lanes', 1) > 1 else ''
        dirs = f" in {s['dirs']} directions" if s.get('dirs', 1) > 1 else ' forward'
        parts.append(f"eruptions along the ground{dirs}, {s.get('len', 12)} blocks{lanes}")
        if d:
            parts.append(f'{d:g} damage')
    elif t == 'zone':
        where = 'around you (follows you)' if s.get('at') == 'self' else 'at your aim'
        parts.append(f"{s.get('r', 4):g}-block field {where} for {s.get('dur', 5):g}s")
        if d:
            parts.append(f'{d:g} damage per second')
        if s.get('pull'):
            parts.append('drags foes to the centre')
    elif t == 'nova':
        where = {'aim': 'at your aim', 'front': 'just in front of you'}.get(s.get('at'), 'around you')
        parts.append(f"{s.get('r', 6):g}-block blast {where}")
        if d:
            parts.append(f'{d:g} damage')
    elif t == 'rain':
        parts.append(f"{s.get('n', 8)} strikes over {s.get('r', 4):g} blocks around your aim, one every {s.get('every', 3) / 20:.2f}s")
        if d:
            parts.append(f'{d:g} damage each')
    elif t == 'meteor':
        n = s.get('n', 1)
        parts.append(f"{n} falling bolt{'s' if n > 1 else ''} from the sky" + (f" over {s['r']:g} blocks" if s.get('r') else '') + f", {s.get('aoe', 3):g}-block blast")
        if d:
            parts.append(f'{d:g} damage{" each" if n > 1 else ""}')
    elif t == 'buff':
        who = f"you and allies within {s['allies']} blocks" if s.get('allies') else 'you'
        parts.append(f"{who}: {effects(s.get('self', []))}")
    elif t == 'heal':
        parts.append(f"heals you and allies within {s.get('r', 6):g} blocks for {s.get('heal', 6):g} HP" + (f", regeneration {s['regen']:g}s" if s.get('regen') else '') + ', removes poison/wither/slowness/weakness/blindness/nausea')
    elif t == 'prison':
        parts.append(f"locks every foe within {s.get('r', 3):g} blocks of your aim in place for {s.get('dur', 3):g}s, then {d:g} damage" if d else f"locks foes in place for {s.get('dur', 3):g}s")
    elif t == 'summon':
        parts.append(f"raises {s.get('n', 1)} ally construct{'s' if s.get('n', 1) > 1 else ''} for {s.get('life', 30)}s")
    elif t == 'wall':
        parts.append(f"a {s.get('w', 5)}×{s.get('h', 3)} wall of {s['block'].split(':')[1].replace('_', ' ')} for {s.get('dur', 8):g}s")
    elif t == 'radial':
        rings = s.get('rings', 1)
        parts.append(f"{s.get('n', 12)} bolts in every direction" + (f", {rings} rings" if rings > 1 else ''))
        if d:
            parts.append(f'{d:g} damage each')
    elif t == 'timestop':
        parts.append(f"freezes every foe within {s.get('r', 10)} blocks for {s.get('dur', 4):g}s and erases hostile spells; {d:g} damage when time flows again")
    elif t == 'leap':
        parts.append(('blink' if s.get('mode') == 'blink' else 'dash') + f" up to {s.get('dist', 8)} blocks, hitting everything on the way")
        if d:
            parts.append(f'{d:g} damage')
    elif t == 'vortex':
        parts.append(f"pulls foes within {s.get('r', 6):g} blocks of your aim together for {s.get('dur', 2):g}s, then bursts")
        if d:
            parts.append(f'{d:g} damage')
    elif t == 'strikes':
        parts.append(f"strikes up to {s.get('n', 4)} foes within {s.get('r', 8):g} blocks of your aim from the sky")
        if d:
            parts.append(f'{d:g} damage each')
    elif t == 'dive':
        parts.append(f"leap high and crash onto your aim ({s.get('r', 4):g}-block impact, you are protected during the dive)")
        if d:
            parts.append(f'{d:g} damage')
    elif t == 'rewind':
        parts.append(f"teleports you back to where you stood ~3s ago and heals {s.get('heal', 6):g} HP")
    elif t == 'repeat':
        parts.append(f"{s.get('n', 3)}× every {s.get('every', 4) / 20:.2f}s: " + describe(s.get('spec', {})))
    if s.get('fire'):
        parts.append(f"sets on fire ({s['fire']:g}s)")
    if s.get('eff') and t not in ('buff',):
        parts.append(effects(s['eff']))
    if s.get('kb'):
        parts.append('knockback')
    if s.get('ls'):
        parts.append(f"heals you for {int(s['ls'] * 100)}% of the damage")
    if s.get('hp'):
        parts.append(f"costs {s['hp']} of your health")
    if s.get('self') and t != 'buff':
        parts.append(f"you gain {effects(s['self'])}")
    text = '; '.join(parts)
    if s.get('then'):
        text += '; then ' + describe(s['then'])
    return text


def table(head, rows):
    o = '| ' + ' | '.join(head) + ' |\n|' + '---|' * len(head) + '\n'
    for r in rows:
        o += '| ' + ' | '.join(str(c).replace('\n', '<br>') for c in r) + ' |\n'
    return o + '\n'


def write(name, title, body):
    path = os.path.join(DOCS, name)
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(HEADER + f'# {title}\n\n' + NAV + body.rstrip() + '\n')
    return path


