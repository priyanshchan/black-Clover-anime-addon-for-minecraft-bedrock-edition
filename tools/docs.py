def strip(s):
    return re.sub(r'§.', '', s or '').strip()


def walk(base):
    for dp, _, fs in os.walk(base):
        for f in sorted(fs):
            if f.endswith('.json'):
                yield os.path.join(dp, f)


def load(p):
    with open(p, encoding='utf-8') as fh:
        return json.load(fh)


# ======================================================================================
# read the built packs
# ======================================================================================
LANG = {}
for line in open(os.path.join(RP, 'texts', 'en_US.lang'), encoding='utf-8'):
    if '=' in line:
        k, v = line.rstrip('\n').split('=', 1)
        LANG[k] = strip(v)

ITEMS = {}
for p in walk(os.path.join(BP, 'items')):
    it = load(p)['minecraft:item']
    ident = it['description']['identifier']
    ITEMS[ident] = strip(it['components'].get('minecraft:display_name', {}).get('value', ident))
for p in walk(os.path.join(BP, 'blocks')):
    ident = load(p)['minecraft:block']['description']['identifier']
    ITEMS[ident] = LANG.get(f'tile.{ident}.name', ident)

ENTITIES = {}
for p in walk(os.path.join(BP, 'entities')):
    e = load(p)['minecraft:entity']
    ident = e['description']['identifier']
    ENTITIES[ident] = e

SPAWN = {}
for p in walk(os.path.join(BP, 'spawn_rules')):
    r = load(p)['minecraft:spawn_rules']
    SPAWN[r['description']['identifier']] = r

LOOT = {}
for p in walk(os.path.join(BP, 'loot_tables', 'entities')):
    LOOT['loot_tables/entities/' + os.path.basename(p)] = load(p)

RECIPES = []
for p in walk(os.path.join(BP, 'recipes')):
    RECIPES.append(load(p))


def item_name(ident):
    if ident in ITEMS:
        return ITEMS[ident]
    return ident.split(':')[-1].replace('_', ' ').title()


def entity_name(ident):
    return LANG.get(f'entity.{ident}.name', ident.split(':')[-1].replace('_', ' ').title())


