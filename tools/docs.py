def recipe_rows():
    rows = []
    for r in RECIPES:
        if 'minecraft:recipe_shaped' in r:
            rr = r['minecraft:recipe_shaped']
            res = rr['result']
            key = ', '.join(f"{k} = {item_name(v['item'])}" for k, v in rr['key'].items())
            grid = '<br>'.join('`' + row.replace(' ', '·') + '`' for row in rr['pattern'])
            rows.append([f"**{item_name(res['item'])}**" + (f" ×{res['count']}" if res.get('count', 1) > 1 else ''), 'shaped', f'{grid}<br>{key}'])
        elif 'minecraft:recipe_shapeless' in r:
            rr = r['minecraft:recipe_shapeless']
            res = rr['result']
            ing = {}
            for i in rr['ingredients']:
                ing[i['item']] = ing.get(i['item'], 0) + 1
            rows.append([f"**{item_name(res['item'])}**" + (f" ×{res['count']}" if res.get('count', 1) > 1 else ''), 'shapeless',
                         ' + '.join(f"{item_name(k)}{' ×' + str(v) if v > 1 else ''}" for k, v in ing.items())])
    return sorted(rows, key=lambda x: x[0])


